package com.bangbangbang.common;

/**
 * 姓名首字母（通讯录分组用）
 *
 * 只做「常见姓氏 → 拼音首字母」的映射，不做完整拼音转换：
 * 通讯录里的名字绝大多数以姓氏开头，未收录的字统一落到 A，
 * 这样不会因为生僻字导致分组缺失。
 *
 * 之所以抽成公共工具：姓名一旦变更，通讯录里的 letter 必须跟着重算，
 * 同步逻辑与新增联系人都要用同一套规则，否则分组会前后不一致。
 */
public final class NameInitial {

    private static final String[][] TABLE = {
            {"李", "L"}, {"刘", "L"}, {"蓝", "L"}, {"林", "L"}, {"罗", "L"},
            {"马", "M"}, {"王", "W"}, {"吴", "W"}, {"赵", "Z"}, {"张", "Z"}, {"周", "Z"}, {"郑", "Z"},
            {"陈", "C"}, {"曹", "C"}, {"杨", "Y"}, {"姚", "Y"}, {"孙", "S"}, {"沈", "S"},
            {"黄", "H"}, {"何", "H"}, {"胡", "H"}, {"郭", "G"}, {"高", "G"}, {"徐", "X"}, {"谢", "X"},
            {"梁", "L"}, {"宋", "S"}, {"唐", "T"}, {"许", "X"}, {"邓", "D"}, {"冯", "F"}, {"韩", "H"},
            {"曾", "Z"}, {"彭", "P"}, {"萧", "X"}, {"蔡", "C"}, {"潘", "P"}, {"田", "T"}, {"董", "D"},
            {"袁", "Y"}, {"于", "Y"}, {"余", "Y"}, {"叶", "Y"}, {"蒋", "J"}, {"杜", "D"}, {"苏", "S"},
            {"魏", "W"}, {"程", "C"}, {"吕", "L"}, {"丁", "D"}, {"任", "R"}, {"沈", "S"}, {"姚", "Y"},
            {"卢", "L"}, {"姜", "J"}, {"崔", "C"}, {"钟", "Z"}, {"谭", "T"}, {"陆", "L"}, {"汪", "W"},
            {"范", "F"}, {"金", "J"}, {"石", "S"}, {"廖", "L"}, {"贾", "J"}, {"夏", "X"}, {"韦", "W"},
            {"付", "F"}, {"方", "F"}, {"白", "B"}, {"邹", "Z"}, {"孟", "M"}, {"熊", "X"}, {"秦", "Q"},
            {"邱", "Q"}, {"江", "J"}, {"尹", "Y"}, {"薛", "X"}, {"闫", "Y"}, {"段", "D"}, {"雷", "L"},
            {"侯", "H"}, {"龙", "L"}, {"史", "S"}, {"陶", "T"}, {"黎", "L"}, {"贺", "H"}, {"顾", "G"},
            {"毛", "M"}, {"郝", "H"}, {"龚", "G"}, {"邵", "S"}, {"万", "W"}, {"钱", "Q"}, {"严", "Y"},
            {"覃", "Q"}, {"武", "W"}, {"戴", "D"}, {"莫", "M"}, {"孔", "K"}, {"向", "X"}, {"汤", "T"}
    };

    private NameInitial() {
    }

    /** 取姓名首字对应的拼音首字母，空名或未收录的字返回 A */
    public static String of(String name) {
        if (name == null || name.isEmpty()) {
            return "A";
        }
        String first = name.substring(0, 1);
        for (String[] row : TABLE) {
            if (row[0].equals(first)) {
                return row[1];
            }
        }
        // 英文名直接取首字母大写
        char c = first.charAt(0);
        if (c >= 'a' && c <= 'z') {
            return String.valueOf((char) (c - 32));
        }
        if (c >= 'A' && c <= 'Z') {
            return String.valueOf(c);
        }
        return "A";
    }
}
